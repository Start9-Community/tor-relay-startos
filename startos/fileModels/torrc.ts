import { FileHelper } from '@start9labs/start-sdk'
import { sdk } from '../sdk'
import {
  dataMount,
  lyrebirdPath,
  metricsPort,
  Mode,
  modeDir,
  obfs4Port,
  orPort,
} from '../utils'

/** Rendered from store.json by main; never parsed back. */
export const torrcFile = FileHelper.string({
  base: sdk.volumes.main,
  subpath: 'torrc',
})

/** Read by the dashboard. */
export const statusFile = FileHelper.string({
  base: sdk.volumes.main,
  subpath: 'status.json',
})

export type TorrcInput = {
  mode: Mode
  nickname: string
  contactInfo: string | null
  bandwidthRate: number
  bandwidthBurst: number
  accountingMax: number | null
  address: string
  /** External ORPort StartOS assigned; null or equal to `orPort` means 1:1. */
  assignedOrPort: number | null
  /** A public IPv6 is enabled on the ORPort interface. */
  ipv6: boolean
}

export const torrcHeader =
  '# Generated by the Tor Relay package from store.json on every start. Edits are overwritten.'

/** Never emits SocksPort, HiddenService*, or anything that lets traffic exit. */
export function renderTorrc(c: TorrcInput): string {
  const dir = `${dataMount}/${modeDir(c.mode)}`
  const family = c.ipv6 ? '' : ' IPv4Only'
  const lines = [
    torrcHeader,
    `DataDirectory ${dir}`,
    `ControlSocket ${dir}/control.sock`,
    'SocksPort 0',
    `MetricsPort 127.0.0.1:${metricsPort}`,
    'MetricsPortPolicy accept 127.0.0.1',
    'Log notice stdout',
    '',
    `Nickname ${c.nickname}`,
  ]
  if (c.contactInfo) lines.push(`ContactInfo ${c.contactInfo}`)
  lines.push(`Address ${c.address}`)

  if (c.assignedOrPort !== null && c.assignedOrPort !== orPort) {
    lines.push(`ORPort ${c.assignedOrPort} NoListen${family}`)
    lines.push(`ORPort ${orPort} NoAdvertise${family}`)
  } else {
    lines.push(`ORPort ${orPort}${family}`)
  }

  lines.push(
    'ExitRelay 0',
    'ExitPolicy reject *:*',
    `RelayBandwidthRate ${c.bandwidthRate} KBytes`,
    `RelayBandwidthBurst ${Math.max(c.bandwidthBurst, c.bandwidthRate)} KBytes`,
  )

  if (c.accountingMax !== null && c.accountingMax > 0) {
    lines.push(
      'AccountingStart month 1 00:00',
      `AccountingMax ${c.accountingMax} GBytes`,
    )
  }

  if (c.mode === 'bridge') {
    lines.push(
      '',
      'BridgeRelay 1',
      'BridgeDistribution any',
      `ServerTransportPlugin obfs4 exec ${lyrebirdPath}`,
      `ServerTransportListenAddr obfs4 0.0.0.0:${obfs4Port}`,
      'ExtORPort auto',
    )
  }

  return lines.join('\n') + '\n'
}
